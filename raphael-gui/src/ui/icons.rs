#[component]
pub fn Icon(kind: IconKind) -> Element {
    let paint = if kind.is_filled() {
        r#"fill="currentColor""#
    } else {
        r#"fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="square" stroke-linejoin="miter""#
    };
    let svg = format!(
        r#"<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" {paint}>{}</svg>"#,
        kind.svg_body()
    );
    rsx! {
        span { class: "icon", "aria-hidden": "true", dangerous_inner_html: svg }
    }
}
